export const ROSTER: Contestant[] = NAMES.map((name, i) => {
  const no = i + 1;
  const [color, colorName] = COLORS[i];
  return {
    no,
    code: String(no).padStart(2, '0'),
    name,
    team: TEAMS[i % TEAMS.length],
    color,
    colorName,
  };
});

export function contestantByCode(code: string | null | undefined): Contestant | null {
  if (!code) return null;
  const no = parseInt(code, 10);
  if (!Number.isFinite(no) || no < 1 || no > 40) return null;
  return ROSTER[no - 1] ?? null;
}
